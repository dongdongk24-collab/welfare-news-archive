const normalize = (value) => value.toString().trim().toLowerCase().replace(/\s+/g, " ");
const compactDate = (value) => value.replace(/[^0-9]/g, "");
const pad = (value) => value.toString().padStart(2, "0");
const formatDate = (date) => `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;

function renderArchiveList(entries) {
  const list = document.querySelector("[data-archive-list]");
  if (!list) return;

  const entriesByMonth = entries.reduce((groups, entry) => {
    const monthKey = entry.date.slice(0, 7);
    if (!groups.has(monthKey)) groups.set(monthKey, []);
    groups.get(monthKey).push(entry);
    return groups;
  }, new Map());

  const monthGroups = Array.from(entriesByMonth.entries());
  const newestYear = Number(monthGroups[0]?.[0].slice(0, 4));

  const monthButtons = monthGroups.map(([monthKey, monthEntries], index) => {
    const [year, month] = monthKey.split("-").map(Number);
    const monthLabel = year === newestYear ? `${month}월` : `${year}년 ${month}월`;
    return `
      <button class="archive-month-tab" type="button" role="tab"
        id="archive-tab-${monthKey}" aria-controls="archive-panel-${monthKey}"
        aria-selected="${index === 0}" tabindex="${index === 0 ? "0" : "-1"}"
        data-archive-month="${monthKey}">
        <span>${monthLabel}</span>
        <small>${monthEntries.length}일</small>
      </button>
    `;
  }).join("");

  const monthPanels = monthGroups.map(([monthKey, monthEntries], index) => {
    const cards = monthEntries.map((entry) => `
      <a class="archive-link" href="${entry.href}">
        <span class="date">${entry.label}</span>
        <span class="summary">${entry.summary}</span>
      </a>
    `).join("");

    return `
      <div class="archive-month-panel" role="tabpanel"
        id="archive-panel-${monthKey}" aria-labelledby="archive-tab-${monthKey}"
        ${index === 0 ? "" : "hidden"}>${cards}</div>
    `;
  }).join("");

  list.innerHTML = `
    <div class="archive-month-tabs" role="tablist" aria-label="월 선택">${monthButtons}</div>
    <div class="archive-month-panels">${monthPanels}</div>
  `;

  const tabs = Array.from(list.querySelectorAll("[data-archive-month]"));
  const selectMonth = (selectedTab) => {
    tabs.forEach((tab) => {
      const selected = tab === selectedTab;
      tab.setAttribute("aria-selected", selected.toString());
      tab.tabIndex = selected ? 0 : -1;
      const panel = document.getElementById(`archive-panel-${tab.dataset.archiveMonth}`);
      if (panel) panel.hidden = !selected;
    });
  };

  tabs.forEach((tab, index) => {
    tab.addEventListener("click", () => selectMonth(tab));
    tab.addEventListener("keydown", (event) => {
      if (!["ArrowLeft", "ArrowRight", "Home", "End"].includes(event.key)) return;
      event.preventDefault();
      let nextIndex = index;
      if (event.key === "ArrowLeft") nextIndex = (index - 1 + tabs.length) % tabs.length;
      if (event.key === "ArrowRight") nextIndex = (index + 1) % tabs.length;
      if (event.key === "Home") nextIndex = 0;
      if (event.key === "End") nextIndex = tabs.length - 1;
      selectMonth(tabs[nextIndex]);
      tabs[nextIndex].focus();
    });
  });
}

function bindManualUpdate() {
  const button = document.querySelector("[data-trigger-update]");
  const message = document.querySelector("[data-trigger-message]");
  if (!button || !message) return;

  button.addEventListener("click", async () => {
    const pin = window.prompt("수집 실행 비밀번호가 설정되어 있으면 입력해 주세요. 없으면 빈칸으로 확인을 누르세요.") || "";
    button.disabled = true;
    button.textContent = "수집 실행 요청 중";
    message.textContent = "GitHub Actions에 뉴스 수집 작업을 요청하고 있습니다.";

    try {
      const response = await fetch("/api/trigger-update", {
        method: "POST",
        headers: pin ? { "x-update-pin": pin } : {},
      });
      const data = await response.json().catch(() => ({}));
      if (!response.ok || !data.ok) {
        throw new Error(data.message || "수집 실행 요청에 실패했습니다.");
      }
      message.textContent = data.message || "뉴스 수집 작업을 시작했습니다. 1~3분 뒤 새로고침해 주세요.";
      button.textContent = "수집 요청 완료";
    } catch (error) {
      message.textContent = error.message || "수집 실행 요청에 실패했습니다. Vercel 환경변수를 확인해 주세요.";
      button.textContent = "오늘 자료 수집 실행";
    } finally {
      setTimeout(() => {
        button.disabled = false;
        if (button.textContent === "수집 요청 완료") button.textContent = "오늘 자료 수집 실행";
      }, 3000);
    }
  });
}

function bindDateSearch() {
  const input = document.querySelector("[data-date-search]");
  const message = document.querySelector("[data-date-message]");
  const button = document.querySelector("[data-date-button]");
  const toggle = document.querySelector("[data-calendar-toggle]");
  const calendar = document.querySelector("[data-calendar]");
  const field = document.querySelector(".calendar-field");
  if (!input || !message || !button || !toggle || !calendar || !field) return;

  const availableDates = new Set(archiveEntries.map((entry) => entry.date));
  let selectedDate = archiveEntries[0]?.date || formatDate(new Date());
  let viewDate = new Date(`${selectedDate}T00:00:00`);

  const findEntry = () => {
    const raw = input.value;
    const normalized = normalize(raw);
    const digits = compactDate(raw);

    return archiveEntries.find((entry) => {
      const entryDigits = compactDate(entry.date);
      return entry.date === normalized || entry.label.includes(raw.trim()) || entryDigits === digits;
    });
  };

  const syncMessage = () => {
    const entry = findEntry();
    message.textContent = entry ? `${entry.label} 페이지가 있습니다.` : "아직 해당 날짜의 아카이브가 없습니다.";
  };

  const openCalendar = () => {
    calendar.hidden = false;
    renderCalendar();
  };

  const closeCalendar = () => {
    calendar.hidden = true;
  };

  const toggleCalendar = (event) => {
    event.stopPropagation();
    if (calendar.hidden) openCalendar();
    else closeCalendar();
  };

  const goToDate = () => {
    const entry = findEntry();
    if (entry) {
      window.location.href = entry.href;
      return;
    }

    message.textContent = "아직 해당 날짜의 아카이브가 없습니다.";
  };

  function renderCalendar() {
    const year = viewDate.getFullYear();
    const month = viewDate.getMonth();
    const first = new Date(year, month, 1);
    const start = new Date(year, month, 1 - first.getDay());
    const weekdays = ["일", "월", "화", "수", "목", "금", "토"];

    const days = Array.from({ length: 42 }, (_, index) => {
      const day = new Date(start);
      day.setDate(start.getDate() + index);
      const value = formatDate(day);
      const outside = day.getMonth() !== month;
      const available = availableDates.has(value);
      const selected = value === selectedDate;
      const className = [
        "calendar-day",
        outside ? "outside" : "",
        available ? "available" : "unavailable",
        selected ? "selected" : ""
      ].filter(Boolean).join(" ");

      return `<button class="${className}" type="button" data-calendar-date="${value}">${day.getDate()}</button>`;
    }).join("");

    calendar.innerHTML = `
      <div class="calendar-head">
        <button class="calendar-nav" type="button" aria-label="이전 달" data-calendar-prev>‹</button>
        <div class="calendar-title">${year}년 ${month + 1}월</div>
        <button class="calendar-nav" type="button" aria-label="다음 달" data-calendar-next>›</button>
      </div>
      <div class="calendar-weekdays">${weekdays.map((day) => `<span>${day}</span>`).join("")}</div>
      <div class="calendar-grid">${days}</div>
    `;
  }

  input.value = selectedDate;
  syncMessage();

  input.addEventListener("click", (event) => {
    event.stopPropagation();
    openCalendar();
  });
  input.addEventListener("focus", openCalendar);
  toggle.addEventListener("click", toggleCalendar);
  button.addEventListener("click", goToDate);

  calendar.addEventListener("click", (event) => {
    event.stopPropagation();
    const previous = event.target.closest("[data-calendar-prev]");
    const next = event.target.closest("[data-calendar-next]");
    const day = event.target.closest("[data-calendar-date]");

    if (previous) {
      event.preventDefault();
      viewDate = new Date(viewDate.getFullYear(), viewDate.getMonth() - 1, 1);
      renderCalendar();
      return;
    }

    if (next) {
      event.preventDefault();
      viewDate = new Date(viewDate.getFullYear(), viewDate.getMonth() + 1, 1);
      renderCalendar();
      return;
    }

    if (day) {
      selectedDate = day.dataset.calendarDate;
      input.value = selectedDate;
      viewDate = new Date(`${selectedDate}T00:00:00`);
      syncMessage();
      renderCalendar();
    }
  });

  field.addEventListener("click", (event) => {
    event.stopPropagation();
  });

  document.addEventListener("click", (event) => {
    if (!field.contains(event.target)) closeCalendar();
  });
}

function resultTemplate(item) {
  const stars = "★".repeat(item.rating) + "☆".repeat(5 - item.rating);
  return `
    <article class="result-item">
      <div class="result-meta">${item.dateLabel} · ${item.section} · <span>${stars}</span></div>
      <h3><a href="${item.page}">${item.title}</a></h3>
      <p>${item.summary}</p>
      <p class="source"><a href="${item.url}" target="_blank" rel="noopener noreferrer">원문 보기</a></p>
    </article>
  `;
}

function flattenNewsData(newsData, entry) {
  return (newsData.sections || []).flatMap((section) => {
    return (section.items || []).map((item) => ({
      ...item,
      date: item.date || newsData.date,
      dateLabel: item.dateLabel || entry.label,
      page: item.page || entry.href,
      section: item.section || section.name
    }));
  });
}

async function loadSearchIndex() {
  const dynamicItems = await Promise.all(archiveEntries.map(async (entry) => {
    try {
      const response = await fetch(`data/news-${entry.date}.json`, { cache: "no-store" });
      if (!response.ok) throw new Error(`Missing ${entry.date}`);
      return flattenNewsData(await response.json(), entry);
    } catch (error) {
      return [];
    }
  }));

  const flattened = dynamicItems.flat();
  if (flattened.length) return flattened;

  const response = await fetch("data/search-index.json", { cache: "no-store" });
  return response.json();
}

async function bindKeywordSearch() {
  const input = document.querySelector("[data-keyword-search]");
  const results = document.querySelector("[data-search-results]");
  const count = document.querySelector("[data-result-count]");
  if (!input || !results || !count) return;

  let index = [];
  try {
    index = await loadSearchIndex();
  } catch (error) {
    results.innerHTML = `<p class="empty">검색 데이터를 불러오지 못했습니다. 잠시 뒤 다시 시도해 주세요.</p>`;
    return;
  }

  const renderResults = () => {
    const query = normalize(input.value);
    if (!query) {
      count.textContent = "검색어를 입력하면 누적된 기사 중에서 찾아드립니다.";
      results.innerHTML = "";
      return;
    }

    const terms = query.split(" ").filter(Boolean);
    const matches = index.filter((item) => {
      const haystack = normalize([
        item.dateLabel,
        item.section,
        item.title,
        item.summary,
        item.insight,
        ...(item.subtitles || [])
      ].join(" "));
      return terms.every((term) => haystack.includes(term));
    });

    count.textContent = `${matches.length}건을 찾았습니다.`;
    results.innerHTML = matches.length
      ? matches.map(resultTemplate).join("")
      : `<p class="empty">일치하는 기사가 없습니다. 다른 표현으로 검색해 보세요.</p>`;
  };

  input.addEventListener("input", renderResults);
}

